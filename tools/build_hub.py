#!/usr/bin/env python3
"""Regenerate the repo's derived files from flows/*/flow.json:
  - index.html   the hub page listing every flow and its screens
  - README.md    the same list for GitHub
These files are always rebuilt, never hand-edited, so two flow updates can't conflict on them:
after a rebase or merge, just run this again.

Usage: python3 tools/build_hub.py [repo-root]
"""
import html
import json
import pathlib
import sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
flows = []
for f in sorted((root / "flows").glob("*/flow.json")):
    data = json.loads(f.read_text())
    data["_dir"] = f.parent.name
    flows.append(data)
flows.sort(key=lambda d: (d.get("order", 50), d.get("title", "")))

e = html.escape
cards = []
for fl in flows:
    base = f"flows/{fl['_dir']}/"
    screens = "".join(
        f'<li><a href="{base}{e(s["file"])}"><span class="id">{e(s.get("id", ""))}</span>{e(s["title"])}</a></li>'
        for s in fl.get("screens", [])
    )
    missing = fl.get("missingAssets", [])
    warn = f'<p class="warn">{len(missing)} asset(s) still to add, see HANDOFF.md</p>' if missing else ""
    src = fl.get("source", {})
    cards.append(f'''
    <article class="flow">
      <header>
        <span class="status">{e(fl.get("status", ""))}</span>
        <h2><a href="{base}{e(fl.get("entry", "index.html"))}">{e(fl["title"])}</a></h2>
        <p class="meta">{e(fl.get("device", "mobile"))} · {len(fl.get("screens", []))} screens · exported {e(fl.get("exportedAt", ""))} · {e(src.get("designSystem", ""))}</p>
      </header>
      {warn}
      <ol>{screens}</ol>
      <p class="links"><a href="{base}{e(fl.get("entry", "index.html"))}">Play from the start</a> · <a href="{base}HANDOFF.md">Handoff notes</a> · <a href="{e(src.get("canvas", "#"))}">Canvas source</a></p>
    </article>''')

page = f'''<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Waffles 2.0 prototypes</title>
<!-- Generated by tools/build_hub.py from flows/*/flow.json. Don't edit by hand. -->
<style>
  :root {{ --ink:#0f2c22; --muted:#56615b; --line:rgba(15,44,34,.12); --brand:#076350; --paper:#fffdf8; }}
  * {{ box-sizing: border-box; }}
  body {{ margin:0; font-family: ui-sans-serif, system-ui, sans-serif; color:var(--ink); background:#f5f2e9; }}
  main {{ max-width: 960px; margin: 0 auto; padding: 48px 20px 80px; }}
  h1 {{ margin: 0 0 6px; font-size: 32px; letter-spacing: -.02em; }}
  .lede {{ margin: 0 0 32px; color: var(--muted); }}
  .grid {{ display:grid; grid-template-columns: repeat(auto-fill, minmax(300px, 1fr)); gap: 16px; }}
  .flow {{ background: var(--paper); border:1px solid var(--line); border-radius: 18px; padding: 20px; }}
  .flow h2 {{ margin: 6px 0 4px; font-size: 18px; line-height: 24px; }}
  .flow h2 a {{ color: inherit; text-decoration: none; }}
  .meta, .links {{ margin: 0; font-size: 13px; color: var(--muted); }}
  .links {{ margin-top: 12px; }}
  .links a, ol a {{ color: var(--brand); }}
  .status {{ display:inline-block; padding: 2px 8px; border-radius: 99px; background: #e9f3c4; font-size: 12px; font-weight: 600; text-transform: capitalize; }}
  .warn {{ margin: 10px 0 0; font-size: 13px; color: #7a3a10; }}
  ol {{ margin: 14px 0 0; padding: 0; list-style: none; display:flex; flex-direction:column; gap: 4px; font-size: 14px; }}
  ol a {{ text-decoration: none; }}
  ol a:hover {{ text-decoration: underline; }}
  .id {{ display:inline-block; min-width: 44px; color: var(--muted); font-variant-numeric: tabular-nums; }}
</style>
</head>
<body>
<main>
  <h1>Waffles 2.0 prototypes</h1>
  <p class="lede">Exported from Claude Design. Each flow is self-contained in <code>flows/&lt;flow&gt;/</code>; open one to click through it like a phone.</p>
  <div class="grid">{"".join(cards)}</div>
</main>
</body>
</html>
'''
(root / "index.html").write_text(page)

rows = "\n".join(
    f"| [{fl['title']}](flows/{fl['_dir']}/{fl.get('entry', 'index.html')}) | {fl.get('status', '')} | {fl.get('device', 'mobile')} | {len(fl.get('screens', []))} | {fl.get('exportedAt', '')} | [notes](flows/{fl['_dir']}/HANDOFF.md) |"
    for fl in flows
)
(root / "README.md").write_text(f"""# Waffles 2.0 prototypes

Static, click-through prototypes exported from the Claude Design canvas. Plain HTML, CSS and vanilla JavaScript: no build step. Serve the repo root as-is (GitHub Pages, Vercel, Netlify or `python3 -m http.server`).

<!-- Generated by tools/build_hub.py from flows/*/flow.json. Don't edit by hand. -->

| Flow | Status | Device | Screens | Exported | Handoff |
|---|---|---|---|---|---|
{rows}

## How this repo is organized

- `flows/<flow>/`: one folder per flow, self-contained (its own HTML, CSS, JS and assets). Updating one flow never touches another.
- `flows/<flow>/flow.json`: where it came from (canvas, page, artboard checksums), its screens and tweaks.
- `flows/<flow>/HANDOFF.md`: notes for engineering: states, data, behaviour, open questions.
- `index.html` and this README are generated by `tools/build_hub.py`. Never edit them by hand; if they conflict after a merge, re-run the script.
- `tools/check.py`: checks every link and asset reference resolves.
""")
print(f"hub: {len(flows)} flows")
